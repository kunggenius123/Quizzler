export type QuizQuestion = {
    id: string;
    question: string;
    topic: string;
    rightAnswers: string[];
    wrongAnswers: string[];
    img: string | null;
};

export type QuizPayload = {
    quizId: string;
    sourceType: "notes" | "table";
    knowledge_levels: Record<string, number>;
    questions: QuizQuestion[];
};

